package com.examly.plantcare.service;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Optional;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.http.HttpStatus;
import org.springframework.security.authentication.UsernamePasswordAuthenticationToken;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.context.SecurityContextHolder;
import org.springframework.web.server.ResponseStatusException;

import com.examly.plantcare.entity.CareTask;
import com.examly.plantcare.entity.CareTask.Status;
import com.examly.plantcare.entity.CareTask.TaskType;
import com.examly.plantcare.entity.Plant;
import com.examly.plantcare.entity.User;
import com.examly.plantcare.repository.CareTaskRepository;
import com.examly.plantcare.repository.PlantRepository;
import com.examly.plantcare.repository.UserRepository;

@ExtendWith(MockitoExtension.class)
class CareTaskServiceTest {

    @Mock CareTaskRepository careTasks;
    @Mock PlantRepository plants;
    @Mock UserRepository users;
    CareTaskService service;
    Plant alicesPlant;

    @BeforeEach
    void setUp() {
        service = new CareTaskService(careTasks, plants, users);
        User alice = User.builder().id(1L).username("alice").build();
        alicesPlant = new Plant();
        alicesPlant.setId(10L);
        alicesPlant.setNickname("Fern");
        alicesPlant.setOwner(alice);
        loginAs("alice", "ROLE_STANDARD_PLANT_OWNER");
    }

    @AfterEach
    void clear() {
        SecurityContextHolder.clearContext();
    }

    private void loginAs(String name, String role) {
        SecurityContextHolder.getContext().setAuthentication(
                new UsernamePasswordAuthenticationToken(name, null, List.of(new SimpleGrantedAuthority(role))));
    }

    private CareTask task(Plant plant, Status status, LocalDateTime when) {
        return CareTask.builder().plant(plant).taskType(TaskType.WATERING).status(status)
                .scheduledDate(when).autoGenerated(true).build();
    }

    @Test
    void generateSchedulePlansAllTaskTypesOverThirtyDaysWithoutDuplicates() {
        when(plants.findById(10L)).thenReturn(Optional.of(alicesPlant));
        when(careTasks.findByPlantId(10L)).thenReturn(new ArrayList<>());
        when(careTasks.saveAll(any())).thenAnswer(i -> new ArrayList<>((List<CareTask>) i.getArgument(0)));

        List<CareTask> created = service.generateSchedule(10L);

        assertTrue(created.stream().map(CareTask::getTaskType).distinct().count() == 4);
        long waterings = created.stream().filter(t -> t.getTaskType() == TaskType.WATERING).count();
        assertTrue(waterings >= 9 && waterings <= 11, "watering every 3 days over 30 days, got " + waterings);
        assertTrue(created.stream().allMatch(t -> t.getStatus() == Status.PENDING
                && Boolean.TRUE.equals(t.getAutoGenerated()) && t.getScheduledDate().isAfter(LocalDateTime.now())));
        for (int i = 1; i < created.size(); i++) {
            assertFalse(created.get(i).getScheduledDate().isBefore(created.get(i - 1).getScheduledDate()));
        }
    }

    @Test
    void generateScheduleSkipsTypesThatAlreadyHavePendingAutoTasks() {
        when(plants.findById(10L)).thenReturn(Optional.of(alicesPlant));
        when(careTasks.findByPlantId(10L)).thenReturn(List.of(task(alicesPlant, Status.PENDING, LocalDateTime.now().plusDays(1))));
        when(careTasks.saveAll(any())).thenAnswer(i -> new ArrayList<>((List<CareTask>) i.getArgument(0)));

        List<CareTask> created = service.generateSchedule(10L);

        assertTrue(created.stream().noneMatch(t -> t.getTaskType() == TaskType.WATERING));
    }

    @Test
    void otherUsersCannotUseSomeoneElsesPlantOrTasks() {
        loginAs("bob", "ROLE_STANDARD_PLANT_OWNER");
        CareTask alicesTask = task(alicesPlant, Status.PENDING, LocalDateTime.now().plusDays(1));
        alicesTask.setId(5L);
        when(plants.findById(10L)).thenReturn(Optional.of(alicesPlant));
        when(careTasks.findById(5L)).thenReturn(Optional.of(alicesTask));
        when(careTasks.findAll()).thenReturn(List.of(alicesTask));

        ResponseStatusException e = assertThrows(ResponseStatusException.class, () -> service.generateSchedule(10L));
        assertEquals(HttpStatus.NOT_FOUND, e.getStatus());
        assertThrows(ResponseStatusException.class, () -> service.markComplete(5L));
        assertThrows(ResponseStatusException.class, () -> service.delete(5L));
        assertTrue(service.getTasks(null, null, null).isEmpty());
        verify(careTasks, never()).delete(any());
    }

    @Test
    void adminCanSeeEveryonesTasks() {
        loginAs("root", "ROLE_ADMIN");
        when(careTasks.findAll()).thenReturn(List.of(task(alicesPlant, Status.PENDING, LocalDateTime.now().plusDays(1))));

        assertEquals(1, service.getTasks(null, null, null).size());
    }

    @Test
    void markCompleteSetsStatusDateAndCompletedBy() {
        User alice = alicesPlant.getOwner();
        CareTask t = task(alicesPlant, Status.PENDING, LocalDateTime.now().minusHours(1));
        t.setId(7L);
        when(careTasks.findById(7L)).thenReturn(Optional.of(t));
        when(users.findByUsername("alice")).thenReturn(Optional.of(alice));
        when(careTasks.save(any())).thenAnswer(i -> i.getArgument(0));

        CareTask done = service.markComplete(7L);

        assertEquals(Status.COMPLETED, done.getStatus());
        assertNotNull(done.getCompletedDate());
        assertSame(alice, done.getCompletedBy());
    }

    @Test
    void statisticsCountsTasksAndCompletionRate() {
        LocalDateTime now = LocalDateTime.now();
        when(careTasks.findAll()).thenReturn(List.of(
                task(alicesPlant, Status.COMPLETED, now.minusDays(2)),
                task(alicesPlant, Status.COMPLETED, now.minusDays(1)),
                task(alicesPlant, Status.PENDING, now.minusHours(3)),
                task(alicesPlant, Status.PENDING, now.plusDays(1))));

        Map<String, Object> stats = service.statistics();

        assertEquals(4, stats.get("total"));
        assertEquals(2L, stats.get("completed"));
        assertEquals(2L, stats.get("pending"));
        assertEquals(1L, stats.get("overdue"));
        assertEquals(50.0, stats.get("completionRate"));
    }
}
